"""Exceptional divisors of a toric resolution of Z and their Igusa constants.

Z = Spec k[S] is normal (g2_saturation_full.py), so Z is the affine toric variety of the cone
sigma = cone(u_F) spanned by the 11 facet normals u_F of cone(S).  Torus-invariant divisors on
any toric modification correspond to primitive lattice vectors u in sigma, with
    a(u) = <lam, u>,  b(u) = <m_omega, u>,  beta(u) = b/a   (when a > 0).
We list the singular faces of sigma (cones not generated by part of a Z-basis) and the lattice
vectors in them of small height that a resolution must or may introduce, with their beta.
"""
import itertools
import numpy as np
from fractions import Fraction
import sympy as sp

rays = {
    'E_reg(beta=1)': (1, 1, 1, 1, 2, 3, 4), 'E_b(beta=2)': (1, 0, 1, 0, 0, 0, 1),
    'E_a(beta=2)': (1, 1, 0, 0, 1, 2, 2), 'E_0ad(beta=3)': (2, 1, 0, 0, 0, 1, 1),
    'E_0ae=E_0az(beta=11/3)': (3, 1, 0, 0, 0, 0, 0), 'E_0bz(beta=4)': (2, 0, 1, 0, 0, 0, 0),
    'E_triv(beta=7)': (1, 0, 0, 0, 0, 0, 0),
    'D_wz': (0, 0, 0, 0, 0, 0, 1), 'D_we': (0, 0, 0, 0, 0, 1, 0), 'D_wd': (0, 0, 0, 0, 1, 0, 0),
    'D_wg': (0, 0, 0, 1, 0, 0, 0)}
names = list(rays)
U = np.array([rays[n] for n in names])
E = np.eye(7, dtype=int)
roots = {'a': (1, 0), 'b': (0, 1), 'g': (1, 1), 'd': (2, 1), 'e': (3, 1), 'z': (3, 2)}
widx = {'g': 3, 'd': 4, 'e': 5, 'z': 6}


def xvec(r):
    ma, mb = roots[r]
    v = E[0] - ma * E[1] - mb * E[2]
    if r in widx:
        v = v + E[widx[r]]
    return v


G = np.array([E[i] for i in range(7)] + [xvec(r) for r in roots])
lam = E[0]
m_omega = E[0] + sum(xvec(r) for r in roots)


def is_face(idx):
    """rays idx span a face of sigma iff the generators of S vanishing on all of them
    vanish on no other ray."""
    zero = [g for g in G if all(np.dot(g, U[i]) == 0 for i in idx)]
    if not zero:
        return False
    s = sum(zero)
    others = [j for j in range(len(U)) if j not in idx]
    return all(np.dot(s, U[j]) > 0 for j in others)


faces = []
for k in range(2, 8):
    for idx in itertools.combinations(range(len(U)), k):
        if is_face(idx):
            faces.append(idx)


def smooth(idx):
    M = sp.Matrix(U[list(idx)].tolist())
    if M.rank() < len(idx):
        return False
    # part of a Z-basis iff gcd of maximal minors is 1
    minors = [M.extract(list(range(len(idx))), list(c)).det()
              for c in itertools.combinations(range(7), len(idx))]
    return sp.igcd(*[int(m) for m in minors]) == 1


sing = [f for f in faces if not smooth(f)]
# keep minimal singular faces
minimal = [f for f in sing if not any(set(g) < set(f) for g in sing)]
print(f"{len(faces)} faces of sigma (dim>=2); {len(sing)} singular; minimal singular faces:")
for f in minimal:
    print("  ", [names[i] for i in f])

print("\nLattice vectors u = sum c_i u_i (0 < c_i < 1 not required; small integer/half combos)"
      "\ninside minimal singular faces, with a(u) > 0, and their beta:")
seen = set()
for f in minimal:
    V = U[list(f)]
    # lattice points in the half-open parallelepiped of the face (fractional parts)
    M = sp.Matrix(V.T.tolist())
    for coeffs in itertools.product([Fraction(j, 6) for j in range(6)], repeat=len(f)):
        if all(c == 0 for c in coeffs):
            continue
        u = sum(float(c) * V[i] for i, c in enumerate(coeffs))
        if np.allclose(u, np.round(u)):
            u = tuple(int(round(t)) for t in u)
            if u in seen:
                continue
            seen.add(u)
            a = int(np.dot(lam, u)); b = int(np.dot(m_omega, u))
            if a > 0:
                vanish_x = [r for r in roots if np.dot(xvec(r), u) > 0]
                print(f"  in {[names[i] for i in f]}: u={u} a={a} b={b} beta={Fraction(b, a)}"
                      f"  x-coords vanishing: {vanish_x}")
