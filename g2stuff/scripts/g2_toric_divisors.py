"""Independent checks of the monomial variety Z of Section 3 (G = G_2).

Torus coordinates (the dense torus of Z):
    lam, z_a, z_b, w_g, w_d, w_e, w_z      (7 coordinates, Z has dimension 7)
Coordinate functions of Z are monomials in these:
    lam, z_a, z_b, w_g, w_d, w_e, w_z,
    x_rho = lam * w_rho / prod_alpha z_alpha^{m_alpha(rho)}   (w_alpha = 1 for simple alpha)
Z = Spec k[S], S the semigroup generated by the 13 exponent vectors.

Checks:
  1. Is S saturated (Z normal)?  Compared lattice points of the cone with S up to degree 4 in lam.
  2. Facets of cone(S) = torus-invariant prime divisors of (the normalization of) Z.
     For each facet with <lam,u> > 0 (a branch of lam = 0) print
        a(E) = <lam,u>,  b(E) = <m_omega,u>,  beta(E) = b/a,
     where omega = d lam ^ dx_alpha ^ ... ^ dx_zeta, m_omega = sum of exponent vectors of
     lam and the six x's (omega = const * chi^{m_omega} * dlog-form, and dlog-form has a
     simple pole along every invariant divisor, so ord_E(omega) = <m_omega,u> - 1).
     Also print which coordinate functions vanish on E (so the image orbit can be read off).
  3. Which essential/Richardson patches of Sections 3-4 meet each divisor
     (patch {m != 0} meets D_u iff <m,u> = 0).
"""
import itertools
import numpy as np
from fractions import Fraction
from scipy.optimize import linprog
from scipy.spatial import ConvexHull

names = ['lam', 'z_a', 'z_b', 'w_g', 'w_d', 'w_e', 'w_z']
E = np.eye(7, dtype=int)
roots = {  # positive roots of G_2: (m_alpha, m_beta)
    'a': (1, 0), 'b': (0, 1), 'g': (1, 1), 'd': (2, 1), 'e': (3, 1), 'z': (3, 2)}
widx = {'g': 3, 'd': 4, 'e': 5, 'z': 6}


def xvec(r):
    ma, mb = roots[r]
    v = E[0] - ma * E[1] - mb * E[2]
    if r in widx:
        v = v + E[widx[r]]
    return v


coord = {'lam': E[0], 'z_a': E[1], 'z_b': E[2]}
for r in widx:
    coord['w_' + r] = E[widx[r]]
for r in roots:
    coord['x_' + r] = xvec(r)
gens = np.array(list(coord.values()))
gnames = list(coord.keys())

# ---------- 1. saturation ----------
level_gens = [coord['x_' + r] for r in roots] + [coord['lam']]  # lam-degree-1 generators


def in_S(v):
    k = v[0]
    for combo in itertools.combinations_with_replacement(range(len(level_gens)), k):
        s = sum((level_gens[i] for i in combo), np.zeros(7, dtype=int))
        if np.all(v[1:] - s[1:] >= 0):
            return True
    return False


def in_cone(v):
    # v = sum c_i g_i, c_i >= 0 (g_i over all 13 generators)
    res = linprog(np.zeros(len(gens)), A_eq=gens.T, b_eq=v, bounds=[(0, None)] * len(gens),
                  method='highs')
    return res.status == 0


bad = []
for k in range(1, 5):
    cnt = 0
    for za in range(-3 * k, 1):
        for zb in range(-2 * k, 1):
            for w in itertools.product(range(0, k + 1), repeat=4):
                v = np.array([k, za, zb, *w])
                # minimal-candidate filter: only test points not dominating a known S element cheaply
                if in_S(v):
                    continue
                if in_cone(v):
                    bad.append(v)
                cnt += 1
    print(f"degree {k}: lattice points of cone not in S found so far: {len(bad)}")
print("Saturated up to lam-degree 4:", len(bad) == 0)
if bad:
    print("examples:", [list(b) for b in bad[:10]])

# ---------- 2. facets ----------
f = np.array([20, 1, 1, 1, 1, 1, 1])  # positive on all generators (cone is pointed)
assert np.all(gens @ f > 0)
pts = np.array([g / (g @ f) for g in gens], dtype=float)
# project to the hyperplane f = 1 (6-dim affine space): use an orthonormal basis
Q, _ = np.linalg.qr(np.column_stack([f] + [E[i] for i in range(1, 7)]).astype(float))
basis = Q[:, 1:]
proj = pts @ basis
hull = ConvexHull(proj)
facets = set()
for eq in hull.equations:
    # facet normal in the 6-dim space -> pick generators on facet, then compute integer normal
    on = [i for i in range(len(gens)) if abs(proj[i] @ eq[:-1] + eq[-1]) < 1e-9]
    M = gens[on]
    # integer normal u with M u = 0 : null space
    import sympy
    ns = sympy.Matrix(M.tolist()).nullspace()
    assert len(ns) == 1, (on, len(ns))
    u = ns[0]
    den = sympy.ilcm(*[sympy.fraction(t)[1] for t in u])
    u = [int(t * den) for t in u]
    g = int(np.gcd.reduce(u))
    u = [t // g for t in u]
    if min(int(np.dot(u, gg)) for gg in gens) < 0:
        u = [-t for t in u]
    facets.add(tuple(u))

m_omega = coord['lam'] + sum(coord['x_' + r] for r in roots)
print("\nm_omega =", list(m_omega))
patches = {
    # Richardson patches Z_{S1}: z(alpha) != 0 for alpha not in S1, x(alpha) != 0 for alpha in S1
    'Z_{a,b} (S1=Delta)': coord['x_a'] + coord['x_b'],
    'Z_a': coord['x_a'] + coord['z_b'],
    'Z_b': coord['z_a'] + coord['x_b'],
    'Z_empty': coord['z_a'] + coord['z_b'],
}
for r in 'gdez':
    patches[f'Z_(0,a,{r})'] = coord['z_b'] + coord['x_' + r] + coord['w_' + r]
    patches[f'Z_(0,b,{r})'] = coord['z_a'] + coord['x_' + r] + coord['w_' + r]

print("\nBranches of lam = 0 on Z (torus-invariant divisors with <lam,u> > 0):")
rows = []
for u in sorted(facets):
    a = int(np.dot(u, coord['lam']))
    if a <= 0:
        continue
    b = int(np.dot(u, m_omega))
    vanish = [n for n in gnames if np.dot(u, coord[n]) > 0]
    meets = [p for p, m in patches.items() if np.dot(u, m) == 0]
    rows.append((Fraction(b, a), a, b, u, vanish, meets))
for beta, a, b, u, vanish, meets in sorted(rows):
    print(f"u={u}  a={a}  b={b}  beta={beta}  beta-1={beta-1}")
    print(f"     vanishing coords: {vanish}")
    print(f"     met by patches:   {meets}")
print("\nOther invariant divisors (<lam,u> = 0):")
for u in sorted(facets):
    if np.dot(u, coord['lam']) == 0:
        vanish = [n for n in gnames if np.dot(u, coord[n]) > 0]
        meets = [p for p, m in patches.items() if np.dot(u, m) == 0]
        print(f"u={u} vanishing {vanish}; met by {meets}")
uncovered = [u for u in facets if not any(np.dot(u, m) == 0 for m in patches.values())]
print("\nInvariant divisors met by none of the listed patches:", uncovered)
